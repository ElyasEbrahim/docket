"""Was `pgdocket compare` right? Check its verdict against every human label (no API calls).

`pgdocket compare k8s_route 2` judged all 300 issues of demo.k8s_live under v2 and re-asked v1. A user would see
the labels in docket.label: 80 drawn at random, plus the disagreements they labelled after `--export-disagreements`.
Every issue also carries the SIG people applied (column `sig`), so the same stored answers can be scored on all
300 rows, and the report from a smaller sample, or from random labels alone, recomputed from the same answers.
"""
import json
import os

from pgdocket import compare

from .db import connect


def run(name="k8s_route", version=2, out_dir="results/compare-k8s-descriptions"):
    with connect() as conn:
        data = compare.fetch(conn, name, version)
        truth = dict(conn.execute("SELECT number::text, sig FROM demo.k8s_live").fetchall())
        order = [r[0] for r in conn.execute(                     # the order compare_enqueue sampled in (seed 1)
            "SELECT c.row_key FROM docket.current c JOIN docket.decision d ON d.id = c.decision_id "
            "LEFT JOIN docket.label l ON l.decision_id = c.decision_id AND l.row_key = c.row_key AND l.sampling = 'random' "
            "WHERE d.name = %s AND c.version = %s ORDER BY (l.row_key IS NOT NULL) DESC, md5(c.row_key || ':1')",
            (name, data["active"])).fetchall()]
    so, sn, rows = data["spec_old"], data["spec_new"], data["rows"]
    rank = {k: i for i, k in enumerate(order)}
    random_only = [r if r["sampling"] == "random" else r | {"label": None, "sampling": None} for r in rows]
    first150 = sorted(sorted(random_only, key=lambda r: rank[r["row_key"]])[:150], key=lambda r: r["row_key"])
    everyone = [r | {"label": truth[r["row_key"]], "sampling": "random"} for r in rows]
    used = [("80 random-sample labels", random_only), ("a 150-row sample, 80 random labels", first150),
            ("80 random labels + the disagreements", rows), ("all 300 human labels", everyone)]
    runs = [(title, compare.analyse(so, sn, rs), sum(r["label"] is not None for r in rs)) for title, rs in used]
    keys = ("n", "labels", "disagreements", "disagreements_labelled", "disagreements_right", "sign_test_p", "changed",
            "noise", "excess", "excess_ci", "accuracy_old", "accuracy_new", "gain_from", "accuracy_gain",
            "accuracy_gain_ci", "calibration", "verdict", "tokens_per_row_old", "tokens_per_row_new")
    out = {title: {k: r[k] for k in keys if k in r} | {"labels_used": n} for title, r, n in runs}
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "validation.json"), "w") as f:
        json.dump(out, f, indent=2, default=float)
    pct = lambda x: "–" if x is None else f"{100 * x:.1f} %"
    pp = lambda x, ci: f"{100 * x:+.1f} pp [{100 * ci[0]:+.1f}, {100 * ci[1]:+.1f}]"
    L = ["# Was the comparison right? (all 300 human labels)", "",
         "The same stored answers (v1 live, v1 re-asked, v2), scored with the labels a user would have at each step "
         "and with the SIG people applied to every issue. No API calls. Generated by `jevbench comparevalidate`.", "",
         "| labels used | rows | labels | due to the change | accuracy v1 → v2 | difference | auto-accept v1 → v2 | verdict |",
         "| --- | ---: | ---: | --- | --- | --- | --- | --- |"]
    auto = lambda r: "–" if not r.get("calibration") else " → ".join(
        "none" if x is None or x["auto_share"] is None else pct(x["auto_share"])
        for x in (r["calibration"]["current"], r["calibration"]["new"]))
    for title, r, n in runs:
        L.append(f"| {title} | {r['n']} | {n} | {pct(r['excess'])} [{pct(r['excess_ci'][0])}, {pct(r['excess_ci'][1])}] | "
                 f"{pct(r.get('accuracy_old'))} → {pct(r.get('accuracy_new'))} | "
                 f"{pp(r['accuracy_gain'], r['accuracy_gain_ci'])} ({r['gain_from']}) | {auto(r)} | {r['verdict']} |")
    w, p = runs[-1][1]["disagreements_right"], runs[-1][1]["sign_test_p"]
    L += ["", f"The versions disagree on {runs[-1][1]['disagreements']} issues: v1 was right on {w['current']}, v2 on "
          f"{w['new']}, neither on {w['neither']} (exact sign test p = {p:.2f}).", "",
          "Auto-accept: the share of compared rows above each version's guaranteed threshold for ≥ 90 % precision "
          "(95 % confidence), with both versions calibrated on the same random labels.", ""]
    with open(os.path.join(out_dir, "validation.md"), "w") as f:
        f.write("\n".join(L))
    return out_dir
